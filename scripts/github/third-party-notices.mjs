/**
 * Print a Markdown table of direct npm dependencies and their declared licenses.
 * Usage: node scripts/github/third-party-notices.mjs
 */
import { readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8"));
const lock = JSON.parse(readFileSync(new URL("../../package-lock.json", import.meta.url), "utf8"));
const names = [
  ...Object.keys(pkg.dependencies ?? {}),
  ...Object.keys(pkg.devDependencies ?? {}),
].sort();

function row(name) {
  const locked = lock.packages?.[`node_modules/${name}`] ?? {};
  let meta = {};
  try {
    meta = JSON.parse(
      readFileSync(new URL(`../../node_modules/${name}/package.json`, import.meta.url), "utf8"),
    );
  } catch {
    meta = {};
  }
  const version = locked.version || meta.version || "";
  const license = meta.license || locked.license || "unknown";
  const repoRaw =
    meta.repository?.url ||
    (typeof meta.repository === "string" ? meta.repository : "") ||
    meta.homepage ||
    "";
  const repo = String(repoRaw)
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^ssh:\/\/git@github\.com\//, "https://github.com/")
    .replace(/^git@github\.com:/, "https://github.com/")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "")
    .replace(/\/$/, "");
  const upstream = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repo)
    ? `https://github.com/${repo}`
    : repo;
  const safe = (value) => String(value).replaceAll("|", "\\|");
  return `| ${safe(name)} | ${safe(version)} | ${safe(license)} | ${safe(upstream)} |`;
}

process.stdout.write(`# Third-party notices

Direct dependencies declared in \`package.json\`, with the license field from each installed package. This is not a full transitive bill of materials. The release workflow can attach an npm CycloneDX SBOM.

Generated by \`node scripts/github/third-party-notices.mjs\`. Re-run after dependency changes and review the diff.

| Package | Version | License | Upstream |
| --- | --- | --- | --- |
${names.map(row).join("\n")}
`);
